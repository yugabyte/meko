#!/usr/bin/env python3
"""Re-vendor the YugabyteDB protobuf definitions that libs/yb_tsclient needs.

yb_tsclient talks to the tserver's PgClientService over YB's native RPC. It
compiles a small set of YB `.proto` files with prost-build (see build.rs).
Those protos are VENDORED (checked in under libs/yb_tsclient/protos/) so the
build stays hermetic — no YB source tree, toolchain, or network needed to
build the crate. The cost is re-syncing on a YB version bump; this script
makes that one reviewable command instead of a hand copy.

It copies the transitive import closure of the root protos from a YB source
checkout, preserving the `yb/...` layout so `import "yb/..."` resolves under
`-I protos/`, re-applies the local prost-compat edits, records the pin in
protos/version.txt, and prints what changed. google/* well-known types are
NOT vendored — protoc (protoc-bin-vendored, used by build.rs) provides them
from its bundled include.

Usage:
    scripts/vendor-yb-protos.py <yb-src-dir> <version>

    <yb-src-dir>  YugabyteDB checkout root (contains src/yb/...); its git HEAD
                  sha is recorded automatically.
    <version>     release label (e.g. 2025.2.3.0) recorded in version.txt.

Then: cargo build -p yb_tsclient   # protoc validates the fresh set
      git diff                      # review
      git commit
"""

import pathlib
import re
import shutil
import subprocess
import sys

# Roots compiled by build.rs. Keep in sync with libs/yb_tsclient/build.rs.
ROOTS = ["yb/tserver/pg_client.proto", "yb/rpc/rpc_header.proto"]

# prost-build does not emit variants for `allow_alias` enum aliases, so a
# field whose default names an alias generates an accessor referencing a
# nonexistent variant (TableType::DefaultTableType). Rewrite the field default
# to the canonical name for the same value (2). This touches the field
# `[ default = ... ]` clause only — NOT the enum members in common_types.proto.
LOCAL_EDITS = [("default = DEFAULT_TABLE_TYPE", "default = YQL_TABLE_TYPE")]
EDIT_FILES = [
    "yb/master/master_ddl.proto",
    "yb/master/catalog_entity_info.proto",
    "yb/tablet/metadata.proto",
]

VERSION_TXT = """\
**Generated by `scripts/vendor-yb-protos.py` — do not edit by hand.**
YugabyteDB version: {version}
YugabyteDB sha: {sha}
"""


def die(msg: str) -> "typing.NoReturn":  # noqa: F821
    sys.exit(f"vendor-yb-protos: error: {msg}")


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    yb_src = pathlib.Path(sys.argv[1]).expanduser().resolve()
    version = sys.argv[2]
    src_root = yb_src / "src"
    if not (src_root / ROOTS[0]).exists():
        die(f"{src_root / ROOTS[0]} not found — is {yb_src} a YugabyteDB checkout?")

    try:
        sha = subprocess.run(
            ["git", "-C", str(yb_src), "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        die(f"could not read git HEAD of {yb_src} — need a git checkout to record the sha")

    dest = pathlib.Path(__file__).resolve().parent.parent / "libs/yb_tsclient/protos"

    # Transitive closure over `import "..."`, yb/ files only.
    import_re = re.compile(r'^\s*import\s+"([^"]+)"', re.M)
    closure: set[str] = set()
    work = list(ROOTS)
    while work:
        rel = work.pop()
        if rel in closure:
            continue
        f = src_root / rel
        if not f.exists():
            die(f"import {rel!r} not found under {src_root} (unexpected non-google import)")
        closure.add(rel)
        for imp in import_re.findall(f.read_text()):
            if not imp.startswith("google/") and imp not in closure:
                work.append(imp)

    old = {str(p.relative_to(dest)) for p in dest.rglob("*.proto")}
    added = sorted(closure - old)
    removed = sorted(old - closure)

    yb_dir = dest / "yb"
    if yb_dir.exists():
        shutil.rmtree(yb_dir)
    for rel in sorted(closure):
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src_root / rel, out)

    for rel in EDIT_FILES:
        if rel not in closure:
            die(f"expected to edit {rel} but it is not in the closure — "
                "upstream restructured; revisit EDIT_FILES/LOCAL_EDITS")
        p = dest / rel
        s = p.read_text()
        for find, repl in LOCAL_EDITS:
            if find not in s:
                die(f"local edit target {find!r} not found in {rel} — "
                    "upstream changed; revisit the prost allow_alias workaround")
            s = s.replace(find, repl)
        p.write_text(s)

    (dest / "version.txt").write_text(VERSION_TXT.format(version=version, sha=sha))

    print(f"vendored {len(closure)} protos from {yb_src} @ {version} ({sha[:12]})")
    for r in added:
        print(f"  + {r}")
    for r in removed:
        print(f"  - {r}")
    if not added and not removed:
        print("  (no set change vs current vendored tree)")
    print("next: cargo build -p yb_tsclient && git diff && git commit")


if __name__ == "__main__":
    main()
