//! Scenario registry. One module per scenario under `fast/` or `slow/`,
//! each exposing `pub async fn run(&Cluster) -> anyhow::Result<()>` with
//! typed `tokio-postgres`/`reqwest` assertions.
//!
//! Scenarios are auto-registered from the filesystem: the build script
//! ([`build.rs`]) scans the `fast/` and `slow/` dirs and generates the
//! `pub mod` declarations + the `fast()`/`slow()` registries below.
//! Adding a scenario is just dropping a `<name>.rs` into the right
//! subdir — nothing here to edit. The subdir is the category; the file
//! stem is the test name. `.sql` golden workloads are likewise
//! auto-discovered at runtime from `test/e2e/storage/{fast,slow}/*.sql`.
//!
//! The runner [`crate::cluster::Cluster::run_scenario`] handles the
//! recycle/gate/PASS reporting around each — scenarios just assert and
//! return `Ok(())`.

use std::future::Future;
use std::pin::Pin;

use crate::cluster::Cluster;

/// A test name (used in progress/PASS messages and for single-test
/// selection) paired with the scenario future. Boxed so the ordered
/// list can live in a `Vec`.
pub type Scenario<'a> = (
    &'static str,
    Pin<Box<dyn Future<Output = anyhow::Result<()>> + 'a>>,
);

// `fast()` and `slow()`, generated by build.rs from the subdir contents.
include!(concat!(env!("OUT_DIR"), "/scenarios_registry.rs"));
