#!/usr/bin/env python3
"""Generate the UI's extension catalog from the build manifest.

deploy/extensions/extensions.yaml is the source of truth for which externalized
extensions exist and at what version. The picker needs the same list, and a
hand-kept copy drifts the moment someone adds an extension, so it is generated
from the manifest instead.

    python3 scripts/gen-extensions.py            # write src/config/extensions.json
    python3 scripts/gen-extensions.py --check    # exit 1 if the file is stale

Requires PyYAML (deploy/extensions/build.sh already does).
"""

import argparse
import json
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
MANIFEST = HERE.parent.parent / "deploy" / "extensions" / "extensions.yaml"
OUT = HERE.parent / "src" / "config" / "extensions.json"

BANNER = "GENERATED by amp_ui/scripts/gen-extensions.py from deploy/extensions/extensions.yaml — do not edit."


def build() -> str:
    manifest = yaml.safe_load(MANIFEST.read_text())
    entries = []
    known = {e["name"] for e in manifest.get("extensions", [])}

    engines = []
    for eng in manifest.get("engines", []):
        name = eng["name"]
        for ext in eng.get("extensions") or []:
            if ext not in known:
                sys.exit(f"engine {name}: bundles unknown extension {ext!r}")
        engines.append(
            {
                "name": name,
                "label": eng["label"],
                "description": eng.get("description", ""),
                "extensions": list(eng.get("extensions") or []),
            }
        )
    if not engines:
        sys.exit("manifest lists no engines")

    for ext in manifest.get("extensions", []):
        name = ext["name"]
        description = ext.get("description")
        if not description:
            sys.exit(f"{name}: manifest entry has no `description:` — add one, the picker renders it.")
        entry = {"name": name, "version": str(ext["version"]), "description": description}
        # preload => shared_preload_libraries => enabling it restarts the postmaster.
        if ext.get("preload"):
            entry["preload"] = True
        # requires => other extensions whose .control must be mounted alongside
        # this one, or CREATE EXTENSION fails. The controller catalog mirrors it
        # (TestCatalogRequiresMatchesManifest compares the two through this file).
        requires = list(ext.get("requires") or [])
        if requires:
            entry["requires"] = requires
        entries.append(entry)
    if not entries:
        sys.exit("manifest lists no extensions")
    return (
        json.dumps(
            {"_comment": BANNER, "engines": engines, "extensions": entries},
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify the checked-in file is current")
    args = ap.parse_args()

    generated = build()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != generated:
            sys.exit(
                f"{OUT.name} is stale — extensions.yaml changed.\n"
                "Run: npm run gen:extensions (and commit the result)."
            )
        print(f"{OUT.name} is up to date")
        return

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generated)
    print(f"wrote {OUT.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
