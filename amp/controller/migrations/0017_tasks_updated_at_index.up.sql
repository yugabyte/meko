-- Index backing the task change feed (GET /api/v1/tasks?updated_since=...), which
-- orders by updated_at ASC rather than the created_at DESC of the default listing.
--
-- The existing tasks_by_created_at / tasks_by_status / tasks_runnable serve none of
-- it: the YCP reconcile agent polls this feed once per reconcile tick (10s by
-- default) for every environment, so without an index it is a repeating seq scan
-- over the whole task log.
--
-- `updated_at ASC` is load-bearing. YSQL defaults a secondary index's leading
-- column to HASH, which can serve neither the `updated_at >= $n` range seek nor the
-- `ORDER BY updated_at ASC` the feed pages by: both degrade to a storage filter over
-- the whole task log plus a sort, which is the scan this index exists to remove.
-- Measured on the sibling case in 0002_resource_model (branches_gc_due): HASH
-- scanned 10k rows in 627 ms where ASC seeked 5 in 2 ms.
--
-- `id ASC` second so the query's tiebreak is satisfied from the index too. Ties are
-- real here -- a task and its neighbours can be stamped by the same now().
CREATE INDEX IF NOT EXISTS tasks_by_updated_at ON tasks (updated_at ASC, id ASC);
