"""Daily depth-1 branch probe: does the same query cost more on a fork?

Every cycle forks the LRU's default branch, puts an endpoint on the fork, runs
an identical query set against both sides, exports the comparison and tears the
fork down. Answers the question in the branch-depth thread with this LRU's own
data instead of a synthetic one.

    lru_branch_probe_seconds{probe,target,pass}   median latency, target is
                                                  parent or branch, pass is
                                                  cold (first touch of a key)
                                                  or warm (same key again)
    lru_branch_probe_ratio{probe,pass}            branch / parent
    lru_branch_probe_setup_seconds{phase}         fork, endpoint, teardown
    lru_branch_probe_age_seconds                  since the last SUCCEEDED cycle,
                                                  so stale numbers show as stale
    lru_branch_probe_last_attempt_timestamp_seconds
    lru_branch_probe_up                           0 when the last cycle failed

Read the warm ratio as the clean comparison. The parent has weeks of file cache
and a fresh endpoint has none, so the cold ratio is biased in the parent's
favour by an amount this probe cannot separate out. Cold is still the number
worth watching: it is the page-miss path that crossing a fork is expected to
make slower.

The predicates come from the fork at runtime, generated by Postgres with
format() so the literals are correctly typed, and both sides then run byte for
byte the same statements. The query set is the top of this workload's
pg_stat_statements, not invented.
"""

import base64
import json
import os
import re
import statistics
import subprocess
import threading
import time
import urllib.request
from http.server import BaseHTTPRequestHandler, HTTPServer

LRU = os.environ.get("LRU_NAME", "small_temporal")
POOL = os.environ.get("AMP_POOL", "lru-temporal")
CLUSTER = os.environ.get("AMP_CLUSTER", "temporal")
AMP_API = os.environ.get(
    "AMP_API_URL", "http://amp-controller.amp-dev.svc.cluster.local:8080/api/v1"
)
AMP_AUTH = os.environ.get("AMP_AUTH", "admin:admin")
AMP_NS = os.environ.get("AMP_NS", "amp-dev")
EP_CPU = os.environ.get("EP_CPU", "2")
EP_MEM = os.environ.get("EP_MEM", "16Gi")
PARENT_HOST = os.environ.get("PGHOST", "small-temporal-endpoint")
PGPORT = os.environ.get("PGPORT", "55433")
PGUSER = os.environ.get("PGUSER", "cloud_admin")
PGDATABASE = os.environ.get("PGDATABASE", "temporal_lru")
INTERVAL = float(os.environ.get("PROBE_INTERVAL", "86400"))
KEYS = int(os.environ.get("PROBE_KEYS", "25"))
PORT = int(os.environ.get("PORT", "9097"))
PREFIX = "probe-"

PROBES = [
    {
        "name": "executions_point",
        "sampler": "SELECT format('shard_id = %s AND namespace_id = %L::bytea AND workflow_id = %L "
        "AND run_id = %L::bytea', shard_id, namespace_id, workflow_id, run_id) "
        "FROM executions TABLESAMPLE SYSTEM (1) LIMIT {k}",
        "query": "SELECT db_record_version, next_event_id FROM executions WHERE {pred}",
    },
    {
        "name": "history_node_range",
        "sampler": "SELECT format('shard_id = %s AND tree_id = %L::bytea AND branch_id = %L::bytea "
        "AND node_id >= %s', shard_id, tree_id, branch_id, node_id) "
        "FROM history_node TABLESAMPLE SYSTEM (1) LIMIT {k}",
        "query": "SELECT node_id, prev_txn_id, txn_id, data_encoding FROM history_node "
        "WHERE {pred} ORDER BY shard_id, tree_id, branch_id, node_id, txn_id LIMIT 20",
    },
    {
        "name": "history_tree_scan",
        "sampler": "SELECT format('shard_id = %s AND tree_id = %L::bytea', shard_id, tree_id) "
        "FROM history_tree TABLESAMPLE SYSTEM (1) LIMIT {k}",
        "query": "SELECT branch_id, data_encoding FROM history_tree WHERE {pred}",
    },
    {
        "name": "shards_point",
        "sampler": "SELECT format('shard_id = %s', shard_id) FROM shards ORDER BY random() LIMIT {k}",
        "query": "SELECT range_id FROM shards WHERE {pred}",
    },
]

state = {"metrics": [], "up": 0.0, "ts": 0.0, "attempt": 0.0}
TIMING = re.compile(r"^Time: ([\d.]+) ms", re.M)


def amp(path, method="GET", body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(AMP_API + path, data=data, method=method)
    req.add_header("Authorization", "Basic " + base64.b64encode(AMP_AUTH.encode()).decode())
    if data:
        req.add_header("content-type", "application/json")
    with urllib.request.urlopen(req, timeout=60) as r:
        raw = r.read()
    return json.loads(raw) if raw else {}


def wait_task(resp, what, timeout=1800):
    task = resp.get("id") or resp.get("task", {}).get("id")
    if not task:
        raise RuntimeError(f"{what}: no task id in {resp}")
    deadline = time.time() + timeout
    while time.time() < deadline:
        st = amp(f"/tasks/{task}").get("status")
        if st in ("succeeded", "completed", "done"):
            return
        if st in ("failed", "cancelled", "error"):
            raise RuntimeError(f"{what}: task {task} {st}")
        time.sleep(5)
    raise RuntimeError(f"{what}: task {task} timed out")


def psql(host, sql, timing=False):
    script = ("\\timing on\n" if timing else "") + sql
    cmd = [
        "psql",
        "-X",
        "-A",
        "-t",
        "-F",
        "\x1f",
        "--no-psqlrc",
        "-h",
        host,
        "-p",
        PGPORT,
        "-U",
        PGUSER,
        "-d",
        PGDATABASE,
        "-v",
        "ON_ERROR_STOP=1",
        "-f",
        "-",
    ]
    out = subprocess.run(cmd, input=script, capture_output=True, text=True, timeout=900)
    if out.returncode != 0:
        raise RuntimeError(out.stderr.strip()[:400])
    return out.stdout


def sample_predicates(host):
    """Bind values taken from rows that exist, typed by Postgres itself."""
    preds = {}
    for p in PROBES:
        rows = [
            ln for ln in psql(host, p["sampler"].format(k=KEYS) + ";").splitlines() if ln.strip()
        ]
        if not rows:
            raise RuntimeError(f"{p['name']}: sampler returned nothing")
        preds[p["name"]] = rows
    return preds


def run_pass(host, preds):
    """One cold pass then one warm pass of the same statements, in one session."""
    script, order = [], []
    for phase in ("cold", "warm"):
        for p in PROBES:
            for pred in preds[p["name"]]:
                script.append(p["query"].format(pred=pred) + ";")
                order.append((p["name"], phase))
    times = [float(m) / 1000.0 for m in TIMING.findall(psql(host, "\n".join(script), timing=True))]
    if len(times) != len(order):
        raise RuntimeError(f"{host}: {len(times)} timings for {len(order)} statements")
    out = {}
    for (name, phase), t in zip(order, times, strict=True):
        out.setdefault((name, phase), []).append(t)
    return {k: statistics.median(v) for k, v in out.items()}


def resolve():
    pool = next(p for p in amp("/storage-pools?limit=500")["storage_pools"] if p["name"] == POOL)
    cl = next(
        c
        for c in amp(f"/storage-pools/{pool['id']}/clusters?limit=500")["clusters"]
        if c["name"] == CLUSTER
    )
    return pool["id"], cl["id"], cl["default_branch"]["branch_id"]


def drop_branch(base, branch_id):
    eps = f"{base}/branches/{branch_id}/endpoints"
    for ep in amp(eps).get("endpoints", []):
        wait_task(amp(f"{eps}/{ep['id']}", "DELETE"), "drop endpoint", 900)
    wait_task(amp(f"{base}/branches/{branch_id}", "DELETE"), "drop branch", 900)


def reap_orphans(base):
    """A crash between fork and teardown would otherwise leak an endpoint."""
    for b in amp(f"{base}/branches?limit=500").get("branches", []):
        if b["name"].startswith(PREFIX):
            print("reaping orphaned branch", b["name"], flush=True)
            drop_branch(base, b["branch_id"])


def cycle():
    pool_id, cluster_id, parent_branch = resolve()
    name = PREFIX + time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    base = f"/storage-pools/{pool_id}/clusters/{cluster_id}"
    setup, branch_id = {}, None
    reap_orphans(base)
    try:
        t0 = time.time()
        wait_task(
            amp(f"{base}/branches", "POST", {"name": name, "parent_branch_id": parent_branch}),
            "fork",
        )
        branch_id = next(
            b["branch_id"]
            for b in amp(f"{base}/branches?limit=500")["branches"]
            if b["name"] == name
        )
        setup["fork"] = time.time() - t0

        t0 = time.time()
        eps = f"{base}/branches/{branch_id}/endpoints"
        wait_task(
            amp(
                eps, "POST", {"role": "read_write", "resources": {"cpu": EP_CPU, "memory": EP_MEM}}
            ),
            "endpoint",
        )
        ep_id = next(e["id"] for e in amp(eps)["endpoints"] if e["role"] == "read_write")
        host = f"yb-ep-{ep_id}.{AMP_NS}.svc.cluster.local"
        deadline = time.time() + 900
        while True:
            try:
                psql(host, "SELECT 1;")
                break
            except Exception:
                if time.time() > deadline:
                    raise
                time.sleep(10)
        setup["endpoint"] = time.time() - t0

        # Sample on the fork, and read the parent first: whichever side the
        # sampler touches gets its pages faulted in, and biasing towards the
        # fork understates the thing being measured.
        preds = sample_predicates(host)
        parent = run_pass(PARENT_HOST, preds)
        branch = run_pass(host, preds)
    finally:
        t0 = time.time()
        try:
            if branch_id:
                drop_branch(base, branch_id)
        except Exception as e:
            print("teardown failed:", e, flush=True)
        setup["teardown"] = time.time() - t0

    lines = [
        "# TYPE lru_branch_probe_seconds gauge",
        "# TYPE lru_branch_probe_ratio gauge",
        "# TYPE lru_branch_probe_setup_seconds gauge",
    ]
    for (probe, phase), v in sorted(parent.items()):
        lines.append(
            f'lru_branch_probe_seconds{{lru="{LRU}",probe="{probe}",target="parent",pass="{phase}"}} {v:.6f}'
        )
    for (probe, phase), v in sorted(branch.items()):
        lines.append(
            f'lru_branch_probe_seconds{{lru="{LRU}",probe="{probe}",target="branch",pass="{phase}"}} {v:.6f}'
        )
        p = parent.get((probe, phase))
        if p:
            lines.append(
                f'lru_branch_probe_ratio{{lru="{LRU}",probe="{probe}",pass="{phase}"}} {v / p:.4f}'
            )
    for phase, v in setup.items():
        lines.append(f'lru_branch_probe_setup_seconds{{lru="{LRU}",phase="{phase}"}} {v:.1f}')
    return lines


def loop():
    while True:
        try:
            state["metrics"] = cycle()
            state["up"] = 1.0
            state["ts"] = time.time()
        except Exception as e:
            state["up"] = 0.0
            print("cycle failed:", e, flush=True)
        state["attempt"] = time.time()
        time.sleep(INTERVAL)


class H(BaseHTTPRequestHandler):
    def do_GET(self):
        now = time.time()
        age = now - state["ts"] if state["ts"] else 0.0
        body = (
            "\n".join(
                state["metrics"]
                + [
                    "# TYPE lru_branch_probe_up gauge",
                    f'lru_branch_probe_up{{lru="{LRU}"}} {state["up"]}',
                    "# TYPE lru_branch_probe_age_seconds gauge",
                    f'lru_branch_probe_age_seconds{{lru="{LRU}"}} {age:.0f}',
                ]
            )
            + "\n"
        )
        self.send_response(200)
        self.send_header("content-type", "text/plain; version=0.0.4")
        self.end_headers()
        self.wfile.write(body.encode())

    def log_message(self, *a):
        pass


if __name__ == "__main__":
    threading.Thread(target=loop, daemon=True).start()
    HTTPServer(("", PORT), H).serve_forever()
