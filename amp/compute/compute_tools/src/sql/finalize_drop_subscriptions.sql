DO $$
BEGIN
    IF NOT EXISTS(
        SELECT 1
        FROM pg_catalog.pg_tables
        WHERE tablename OPERATOR(pg_catalog.=) 'drop_subscriptions_done'::pg_catalog.name
        AND schemaname OPERATOR(pg_catalog.=) 'neon'::pg_catalog.name
    )
    THEN
        CREATE TABLE yb_amp.drop_subscriptions_done
        (id pg_catalog.int4 primary key generated by default as identity, branch_id pg_catalog.text);
    END IF;

    -- preserve the branch_id of the last drop_subscriptions run
    -- to ensure that the cleanup of a branch is executed only once.
    -- use upsert to avoid the table bloat in case of cascade branching (branch of a branch)
    INSERT INTO yb_amp.drop_subscriptions_done VALUES (1, pg_catalog.current_setting('yb_amp.branch_id'))
    ON CONFLICT (id) DO UPDATE
    SET branch_id = pg_catalog.current_setting('yb_amp.branch_id')::pg_catalog.text;
END
$$
