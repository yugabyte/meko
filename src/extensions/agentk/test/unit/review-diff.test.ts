import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { anchorsLine, generatedByName, readDiff, secretPath } from '../../src/server/review/diff.js';
import { findGuides, findMekoMds } from '../../src/server/review/guides.js';
import { readCommits, readHistory } from '../../src/server/review/history.js';

/** A repo on `main` with one commit (test/helpers.ts has one too, but loads the whole server). */
function gitRepo(dir: string): string {
  mkdirSync(dir, { recursive: true });
  const g = (...a: string[]) => execFileSync('git', a, { cwd: dir, stdio: 'ignore' });
  g('init', '-q', '-b', 'main');
  g('config', 'user.email', 'test@example.com');
  g('config', 'user.name', 'Test');
  writeFileSync(join(dir, 'README.md'), '# test\n');
  g('add', '.');
  g('commit', '-q', '-m', 'init');
  return dir;
}

describe('withholding by path', () => {
  // TestSecretPathsAreRecognisedByPathAlone
  it.each([
    ['.env', true], ['config/.env.production', true], ['prod.env', true], ['.env.example', false], ['.env.sample', false],
    ['deploy/tls.PEM', true], ['id_ed25519', true], ['home/.ssh/config', true], ['keys/server.key', true], ['certs/ca.crt', false],
    ['src/env.ts', false], ['credentials', true],
  ])('%s is a credential path: %s', (p, want) => {
    expect(secretPath(p)).toBe(want);
  });

  // TestGeneratedByNameAcrossEcosystems
  it.each([
    ['package-lock.json', true], ['api/v1/user.pb.go', true], ['web/app.min.js', true], ['__snapshots__/a.test.ts.snap', true],
    ['pkg/zz_generated.deepcopy.go', true], ['vendor/github.com/x/y.go', true], ['src/generated.ts', false], ['main.go', false],
  ])('%s is generated by its name: %s', (p, want) => {
    expect(generatedByName(p)).toBe(want);
  });
});

describe('the change a review reads', () => {
  let dir: string;
  let runDir: string;
  const g = (...a: string[]) => execFileSync('git', a, { cwd: dir, stdio: 'pipe' }).toString();
  const write = (p: string, text: string) => {
    mkdirSync(join(dir, p, '..'), { recursive: true });
    writeFileSync(join(dir, p), text);
  };

  beforeEach(() => {
    const root = mkdtempSync(join(tmpdir(), 'ak-review-diff-'));
    dir = gitRepo(join(root, 'repo'));
    runDir = join(root, 'run');
    write('src/app.ts', 'function start() {\n  a();\n  b();\n  c();\n  open();\n  serve();\n  close();\n}\n');
    write('.env', 'TOKEN=old\n');
    write('package-lock.json', '{}\n');
    write('src/review/REVIEW.md', '# guide\n');
    write('REVIEW.md', '# root guide\n');
    write('src/MEKO.md', '# datapacks\n');
    g('add', '.');
    g('commit', '-q', '-m', 'base: start serves between open and close');
    g('checkout', '-q', '-b', 'feature');
    write('src/app.ts', 'function start() {\n  a();\n  b();\n  c();\n  open();\n  serveTwice();\n  close();\n}\n');
    g('commit', '-qam', 'serve twice\n\nBecause once is not enough.');
  });

  afterEach(() => rmSync(join(dir, '..'), { recursive: true, force: true }));

  it('reads committed, uncommitted and untracked changes, and withholds credentials and generated files', async () => {
    write('src/review/x.ts', 'export const x = 1;\n'); // untracked
    write('.env', 'TOKEN=new\n');
    write('package-lock.json', '{"a":1}\n');
    write('src/gen/api.ts', '// Code generated by protoc. DO NOT EDIT.\nexport {};\n');
    const d = await readDiff(dir, 'main', runDir);
    expect(d.mergeBase.ref).toBe('main');
    expect(d.files.map((f) => [f.path, f.status, f.withheld])).toEqual([
      ['.env', 'modified', 'secret'],
      ['package-lock.json', 'modified', 'generated'],
      ['src/app.ts', 'modified', ''],
      ['src/gen/api.ts', 'added', 'generated'],
      ['src/review/x.ts', 'added', ''],
    ]);
    expect(d.inline).toBe(true);
    expect(d.patch).toContain('+  serveTwice();');
    expect(d.patch).toContain('+export const x = 1;');
    expect(d.patch).not.toContain('TOKEN');
    const app = d.files.find((f) => f.path === 'src/app.ts')!;
    expect(app.symbols).toEqual(['function start() {']);
    expect(app.baseRanges).toEqual([[3, 8]]);
    expect([2, 3, 6, 8].map((n) => anchorsLine(app, n))).toEqual([false, true, true, true]);
  });

  it("obeys the repo's -linguist-generated over the name", async () => {
    write('.gitattributes', 'package-lock.json -linguist-generated\n');
    write('package-lock.json', '{"a":1}\n');
    const d = await readDiff(dir, 'main', runDir);
    expect(d.files.find((f) => f.path === 'package-lock.json')?.withheld).toBe('');
  });

  it('writes a patch per file when the change is too large to inline', async () => {
    const d = await readDiff(dir, 'main', runDir, { inlineMax: 10 });
    expect(d.inline).toBe(false);
    const app = d.files.find((f) => f.path === 'src/app.ts')!;
    expect(app.patchPath).toBe(join(runDir, 'patches', 'src__app.ts.patch'));
    expect(readFileSync(app.patchPath!, 'utf8')).toContain('+  serveTwice();');
  });

  it('gives the history the commits that last wrote the rewritten lines, and the branch its commits', async () => {
    const d = await readDiff(dir, 'main', runDir);
    const history = await readHistory(dir, d.mergeBase.sha, d);
    expect(history).toContain('### src/app.ts');
    expect(history).toContain('Last wrote the lines this PR changes:');
    expect(history).toContain('base: start serves between open and close');
    expect(await readCommits(dir, d.mergeBase.sha)).toEqual([expect.stringMatching(/^[0-9a-f]+ serve twice\n\nBecause once is not enough\.$/)]);
  });

  it("finds the guides and MEKO.md files beside the change's paths, root first", () => {
    expect(findGuides(dir, ['src/review/x.ts', 'src/app.ts'])).toEqual(['REVIEW.md', 'src/review/REVIEW.md']);
    expect(findMekoMds(dir, ['src/review/x.ts'])).toEqual(['src/MEKO.md']);
  });
});
