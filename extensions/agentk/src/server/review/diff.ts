/**
 * The change a local review reads (`diff.go`, `withhold.go`, `generated.go` in agent-k's
 * `pkg/agenticreview`): from where the branch left its base to the working tree, uncommitted and
 * untracked files included, since the PR prompt is what commits them. Each file's patch, the lines a
 * finding may anchor on, the base-side ranges the history blames, and the files whose patches stay
 * out of the prompts: credential paths, and files a generator wrote. Read only: nothing here
 * touches the index or the worktree.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { lstat, open, readFile, readlink } from 'node:fs/promises';
import { basename, join } from 'node:path';
import { diffBase, matchPatches, newFilePatch, parseNameStatus, parseNumstat, splitPatch } from '../changes.js';
import { gitRaw } from '../git.js';
import type { Diff, FileChange, Withheld } from './types.js';

/** The cloud's REVIEW_INLINE_DIFF_BYTES: a patch up to this goes in the prompt whole. */
export const INLINE_MAX = 256 * 1024;

/** Context lines around each hunk; a finding can only anchor on lines the passes were shown. */
const DIFF_CONTEXT = 3;

/** Untracked files are read up to this size each, and this many at most. */
const UNTRACKED_READ_MAX = 1024 * 1024;
const UNTRACKED_MAX_FILES = 2000;

/**
 * `git diff` whose output the parsing here can rely on, whatever the user's config says: paths not
 * octal-escaped, blank context kept, a/ and b/ prefixes, no external drivers or textconv.
 */
function gitDiff(worktree: string, ...args: string[]): Promise<string> {
  return gitRaw(
    worktree, '-c', 'core.quotePath=false', '-c', 'diff.suppressBlankEmpty=false', 'diff',
    '-M', '--no-color', '--no-ext-diff', '--no-textconv', '--no-relative', '--src-prefix=a/', '--dst-prefix=b/', '--submodule=short',
    ...args,
  );
}

// ---- withholding (withhold.go) ----

/** Exact filenames that hold credentials wherever they sit. */
const SECRET_BASENAMES = new Set([
  '.netrc', '_netrc', '.npmrc', '.pypirc', '.dockercfg', '.pgpass', '.htpasswd', 'id_rsa', 'id_dsa', 'id_ecdsa', 'id_ed25519',
  'credentials', 'kubeconfig',
]);
/** Key and keystore formats. `.pem` withholds certificates too: the same extension carries private keys. */
const SECRET_SUFFIXES = ['.pem', '.key', '.p12', '.pfx', '.jks', '.keystore', '.ppk'];
/** Directories whose whole subtree is credential material. */
const SECRET_DIRS = ['.ssh', '.gnupg'];
/** .env-family names that say they hold variable names and no values: required reading, not withheld. */
const ENV_TEMPLATES = new Set(['.env.example', '.env.sample', '.env.template']);

/**
 * A changed path is credential material, by path alone (so it holds for a deleted or binary file),
 * case-insensitively. It fails closed: an unrecognised member of the .env family is withheld.
 */
export function secretPath(p: string): boolean {
  const lower = p.toLowerCase();
  const base = basename(lower);
  if (ENV_TEMPLATES.has(base)) return false;
  if (base === '.env' || base.startsWith('.env.') || base.endsWith('.env')) return true;
  if (SECRET_BASENAMES.has(base)) return true;
  if (SECRET_SUFFIXES.some((s) => base.endsWith(s))) return true;
  return SECRET_DIRS.some((d) => `/${lower}/`.includes(`/${d}/`));
}

// ---- generated files (generated.go) ----

const GENERATED_BASENAMES = new Set([
  'go.sum', 'package-lock.json', 'yarn.lock', 'pnpm-lock.yaml', 'npm-shrinkwrap.json', 'Cargo.lock', 'poetry.lock', 'Pipfile.lock',
  'uv.lock', 'composer.lock', 'Gemfile.lock', 'mix.lock', 'packages.lock.json', 'gradle.lockfile', 'flake.lock',
]);
const GENERATED_SUFFIXES = [
  // protobuf / grpc
  '.pb.go', '.pb.gw.go', '_pb2.py', '_pb2_grpc.py', '.pb.cc', '.pb.h', '_pb.js', '_pb.d.ts', '_pb.rb', '.pb.swift', '.pbobjc.m', '.pbobjc.h',
  // general codegen conventions
  '.gen.go', '_generated.go', '.gen.ts', '.gen.py', '.generated.cs', '_string.go',
  // bundled / minified frontend output and its maps
  '.min.js', '.min.css', '.js.map', '.css.map',
  // test snapshots
  '.snap',
];
const GENERATED_DIRS = ['__snapshots__', 'node_modules', 'vendor/github.com', 'gen-go', 'gen-py', 'gen-cpp', 'gen-java'];
/** Header lines that mean a machine wrote the file, matched in its first lines. */
const GENERATED_MARKERS = ['do not edit', '@generated', 'code generated', 'automatically generated', 'autogenerated', 'auto-generated'];
const GENERATED_HEADER_LINES = 10;

/** The path alone marks the file as generated. */
export function generatedByName(p: string): boolean {
  const base = basename(p);
  if (GENERATED_BASENAMES.has(base)) return true;
  if (GENERATED_SUFFIXES.some((s) => base.endsWith(s))) return true;
  if (base.startsWith('zz_generated')) return true;
  return GENERATED_DIRS.some((d) => `/${p}/`.includes(`/${d}/`));
}

/** The file's first lines carry a generated-code marker. Absent, unreadable or binary files say no. */
async function headerSaysGenerated(worktree: string, path: string): Promise<boolean> {
  let text: string;
  try {
    const f = await open(join(worktree, path), 'r');
    try {
      const buf = Buffer.alloc(64 * 1024);
      const { bytesRead } = await f.read(buf, 0, buf.length, 0);
      text = buf.subarray(0, bytesRead).toString('utf8');
    } finally {
      await f.close();
    }
  } catch {
    return false;
  }
  for (const line of text.split('\n').slice(0, GENERATED_HEADER_LINES)) {
    if (line.includes('\0')) return false;
    const l = line.toLowerCase();
    if (GENERATED_MARKERS.some((m) => l.includes(m))) return true;
  }
  return false;
}

/** Each path's linguist-generated attribute (set, unset, true, false, unspecified); nothing when git can't say. */
async function linguistAttrs(worktree: string, paths: string[]): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (let start = 0; start < paths.length; start += 200) {
    let raw: string;
    try {
      raw = await gitRaw(worktree, 'check-attr', '-z', 'linguist-generated', '--', ...paths.slice(start, start + 200));
    } catch {
      return out;
    }
    const f = raw.split('\0');
    for (let i = 0; i + 2 < f.length; i += 3) out.set(f[i], f[i + 2]);
  }
  return out;
}

/**
 * Why each file's patch is withheld. Secrets first: a file can be both (a vendored `.pem`), and the
 * generated reason would offer it to be read. A repo's explicit `-linguist-generated` is obeyed over
 * the heuristics.
 */
async function markWithheld(worktree: string, files: FileChange[]): Promise<void> {
  for (const f of files) {
    if (secretPath(f.path) || (f.oldPath !== null && secretPath(f.oldPath))) f.withheld = 'secret';
  }
  const attrs = await linguistAttrs(worktree, files.map((f) => f.path));
  for (const f of files) {
    if (f.withheld) continue;
    const a = attrs.get(f.path);
    if (a === 'set' || a === 'true') f.withheld = 'generated';
    else if (a === 'unset' || a === 'false') continue;
    else if (generatedByName(f.path) || (await headerSaysGenerated(worktree, f.path))) f.withheld = 'generated';
  }
  for (const f of files) {
    if (!f.withheld) continue;
    f.deleted = await lstat(join(worktree, f.path)).then(() => false, () => true);
    f.patch = '';
  }
}

// ---- hunks ----

const HUNK = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$/;

/** Fills in a file's anchors, base ranges and hunk symbols from its patch. */
export function readHunks(f: FileChange): void {
  const symbols = new Set<string>();
  for (const line of f.patch.split('\n')) {
    const m = HUNK.exec(line);
    if (!m) continue;
    const baseStart = Number(m[1]), baseCount = m[2] === undefined ? 1 : Number(m[2]);
    const start = Number(m[3]), count = m[4] === undefined ? 1 : Number(m[4]);
    if (baseCount > 0) f.baseRanges.push([baseStart, baseStart + baseCount - 1]);
    // A pure deletion hunk has no new-side lines to anchor on.
    for (let n = start; n < start + count; n++) f.anchors.push(n);
    const sym = m[5].trim();
    if (sym && symbols.size < 10) symbols.add(sym);
  }
  f.symbols = [...symbols];
}

/** The line is inside one of the file's hunks: a finding may anchor there. */
export function anchorsLine(f: FileChange, line: number): boolean {
  return f.anchors.includes(line);
}

/** An untracked file as an added one, with its whole text as the patch (none for a binary or large file). */
async function untrackedFile(worktree: string, path: string): Promise<FileChange> {
  const f = blank(path, null, 'added');
  const full = join(worktree, path);
  try {
    const st = await lstat(full);
    let text: string | null = null;
    if (st.isSymbolicLink()) text = await readlink(full);
    else if (st.isFile() && st.size <= UNTRACKED_READ_MAX) {
      const buf = await readFile(full);
      if (!buf.subarray(0, 8000).includes(0)) text = buf.toString('utf8');
    }
    if (text) {
      const hunk = newFilePatch(text);
      f.additions = hunk.split('\n').filter((l) => l.startsWith('+')).length;
      f.patch = `diff --git a/${path} b/${path}\nnew file mode 100644\n--- /dev/null\n+++ b/${path}\n${hunk}`;
    }
  } catch {
    // Gone since git listed it: it stays in the list with no patch.
  }
  return f;
}

function blank(path: string, oldPath: string | null, status: FileChange['status']): FileChange {
  return {
    path, oldPath, status, additions: 0, deletions: 0, patch: '', withheld: '' as Withheld, anchors: [], baseRanges: [], symbols: [],
    patchPath: null, deleted: false,
  };
}

/** A repo path as one file name, so the patches folder stays one level deep. */
function patchFileName(path: string): string {
  return `${path.split('/').join('__')}.patch`;
}

/**
 * The change from where the branch left `base` (`diffBase`: origin's or upstream's `base`, else the
 * local one) to the working tree. Inline when the patch, withheld files left out, is at most
 * `inlineMax` bytes; otherwise each file's patch is written to `<runDir>/patches/` for the passes
 * to read by its absolute path. Throws when the branch has no history in common with `base`.
 */
export async function readDiff(worktree: string, base: string, runDir: string, opts: { inlineMax?: number } = {}): Promise<Diff> {
  const mb = await diffBase(worktree, base);
  if (!mb) throw new Error(`the branch has no history in common with ${base}`);
  const [status, numstat, whole, others] = await Promise.all([
    gitDiff(worktree, '--name-status', '-z', mb.sha),
    gitDiff(worktree, '--numstat', '-z', mb.sha),
    gitDiff(worktree, `--unified=${DIFF_CONTEXT}`, mb.sha),
    gitRaw(worktree, 'ls-files', '--others', '--exclude-standard', '-z').catch(() => ''),
  ]);
  const entries = parseNameStatus(status);
  const counts = parseNumstat(numstat);
  const patches = matchPatches(entries, splitPatch(whole));
  const files: FileChange[] = entries.map((e, i) => {
    const f = blank(e.path, e.oldPath, e.kind === 'untracked' ? 'added' : e.kind);
    const n = counts.get(e.path);
    f.additions = n?.added ?? 0;
    f.deletions = n?.removed ?? 0;
    f.patch = n?.binary ? '' : patches[i] ?? '';
    return f;
  });
  const extra = others.split('\0').filter((p) => p && !p.endsWith('/')).slice(0, UNTRACKED_MAX_FILES);
  for (const p of extra) files.push(await untrackedFile(worktree, p));
  for (const f of files) readHunks(f);
  await markWithheld(worktree, files);

  const patch = files.filter((f) => !f.withheld && f.patch).map((f) => f.patch).join('\n');
  const inline = patch.length <= (opts.inlineMax ?? INLINE_MAX);
  if (!inline) {
    const dir = join(runDir, 'patches');
    mkdirSync(dir, { recursive: true });
    for (const f of files) {
      if (f.withheld || !f.patch) continue;
      f.patchPath = join(dir, patchFileName(f.path));
      writeFileSync(f.patchPath, `${f.patch}\n`);
    }
  }
  return { files, patch, inline, mergeBase: mb };
}
